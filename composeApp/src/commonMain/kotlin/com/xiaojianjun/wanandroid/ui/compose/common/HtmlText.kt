package com.xiaojianjun.wanandroid.ui.compose.common

private val hiddenContent = Regex("(?is)<(script|style)\\b[^>]*>.*?</\\1>")
private val lineBreak = Regex("(?i)<br\\s*/?>")
private val paragraphEnd = Regex("(?i)</(p|div|h[1-6])\\s*>")
private val htmlTag = Regex("""(?s)<!--.*?-->|</?[A-Za-z](?:[^'\">]|"[^"]*"|'[^']*')*>""")
private val htmlEntity = Regex("&(#(?:x|X)[0-9a-fA-F]+|#[0-9]+|[A-Za-z][A-Za-z0-9]*);")

fun String?.htmlPlainText(): String {
    if (isNullOrEmpty()) return ""
    val text = replace(hiddenContent, "")
        .replace(lineBreak, "\n")
        .replace(paragraphEnd, "\n\n")
        .replace(htmlTag, "")
    return htmlEntity.replace(text) { match ->
        val entity = match.groupValues[1]
        val code = when {
            entity.startsWith("#x", ignoreCase = true) -> entity.drop(2).toIntOrNull(16)
            entity.startsWith("#") -> entity.drop(1).toIntOrNull()
            else -> htmlEntities[entity]
        }
        when {
            code == null || code !in 1..0x10FFFF || code in 0xD800..0xDFFF -> match.value
            code <= 0xFFFF -> code.toChar().toString()
            else -> {
                val value = code - 0x10000
                "${(0xD800 + (value shr 10)).toChar()}${(0xDC00 + (value and 1023)).toChar()}"
            }
        }
    }
}

